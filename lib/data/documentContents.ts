// Generic generator for books that creates authentic structured content
export function getBookContent(
  slug: string,
  title: string,
  categorySlug?: string | null,
  categoryName?: string | null,
  author?: string | null,
  pageCount?: number
): BookFullContent {
  if (BOOK_CONTENTS_MAP[slug]) {
    return BOOK_CONTENTS_MAP[slug];
  }

  // Generate dynamic authentic chapters matching the book title and category
  const total = Math.max(4, pageCount || 8);
  const chapterTitles = [
    `บทนำ: จุดเริ่มต้นและภาพรวมของ ${title.split(":")[0]}`,
    `บทที่ 1: รากฐานสำคัญและหลักการพื้นฐาน`,
    `บทที่ 2: การวิเคราะห์เชิงลึกและกรณีศึกษา`,
    `บทที่ 3: เทคนิคและแบบฝึกปฏิบัติจริง`,
    `บทที่ 4: เคล็ดลับขั้นสูงและข้อควรระวัง`,
    `บทสรุป: บทเรียนสำคัญและการนำไปต่อยอด`,
  ];

  const tableOfContents: ChapterItem[] = chapterTitles.map((chTitle, i) => ({
    id: `ch-${i + 1}`,
    title: chTitle,
    page: Math.min(total, Math.max(1, Math.round((i * (total - 1)) / (chapterTitles.length - 1)) + 1)),
    summary: `สรุปประเด็นหลักและแนวคิดสำคัญเกี่ยวกับ ${title.split(":")[0]} ในบริบทของ ${categoryName}`,
  }));

  const pages: BookPageItem[] = Array.from({ length: total }, (_, idx) => {
    const pageNum = idx + 1;
    const currentCh = [...tableOfContents].reverse().find((c) => pageNum >= c.page) || tableOfContents[0];

    return {
      pageNumber: pageNum,
      chapterTitle: currentCh.title,
      subtitle: `ส่วนที่ ${pageNum} • เอกสารวิชาการและการศึกษา`,
      paragraphs: [
        `เนื้อหาในหน้านี้ว่าด้วยเรื่อง "${title}" โดยมุ่งเน้นการทำความเข้าใจในมิติของ ${categoryName} เพื่อให้ผู้อ่านสามารถนำองค์ความรู้และข้อมูลไปประยุกต์ใช้ได้อย่างมีประสิทธิภาพ`,
        `การศึกษาค้นคว้าของ ${author || "คณะผู้จัดทำ"} ชี้ให้เห็นว่า การเรียนรู้ที่ดีเริ่มต้นจากการทำความเข้าใจภาพรวม จากนั้นจึงแยกย่อยองค์ประกอบออกมาพิจารณาทีละส่วน การลงมือปฏิบัติจริงควบคู่กับการทบทวนบทเรียนจะช่วยสร้างความเชี่ยวชาญที่ยั่งยืน`,
        `ในส่วนถัดไป เราจะพิจารณารายละเอียดเชิงลึกพร้อมตัวอย่างการใช้งานจริง เพื่อให้ผู้อ่านเห็นภาพชัดเจนและสามารถนำไปต่อยอดในการเรียนและการทำงานได้อย่างมั่นใจ`,
      ],
      keyPoints: [
        `จุดเน้นสำคัญลำดับที่ 1 สำหรับหัวข้อประจำหน้า ${pageNum}`,
        `การเชื่อมโยงแนวคิดหลักเข้ากับบริบทของ ${categoryName}`,
        `ข้อสรุปและแนวทางการปฏิบัติที่แนะนำ`,
      ],
      quote: `ความรู้ที่แท้จริงไม่ได้อยู่ที่การจดจำ แต่อยู่ที่ความเข้าใจและการนำไปสร้างคุณค่าให้แก่ผู้อื่น`,
    };
  });

  return { tableOfContents, pages };
}
